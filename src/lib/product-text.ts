/** What staff typed in the "Română" group of a product or category; wins when filled in. */
export type Override = { name?: string | null; shortDescription?: string | null; description?: string | null } | null | undefined

const filled = (v: string | null | undefined): v is string => typeof v === 'string' && v.trim().length > 0

/** A Latin-looking token typed with Cyrillic letters ("М42", "СА20") made Latin, for display. */
function latinize(text: string): string {
  // A lone Cyrillic look-alike inside a Latin word ("Metabо") is a typo for the Latin letter.
  text = text.replace(/(?<=[A-Za-z])[АВЕКМНОРСТХаеорсх]|[АВЕКМНОРСТХаеорсх](?=[A-Za-z])/g, (c) => HOMOGLYPH[c] ?? c)
  return text.replace(/(?<![\p{L}])[АВЕКМНОРСТХ]{1,3}(?=\d)/gu, (m) => [...m].map((c) => HOMOGLYPH[c] ?? c).join(''))
}

export function localizeName(name: string, lang: TextLang, override?: Override): string {
  if (lang === 'bg') return name
  if (filled(override?.name)) return override.name.trim()
  // A homoglyph token ("Лента за банциг Böhlеr", "М42") reads as Latin in the output.
  return latinize(apply(name, NAME_RO)).replace(/(\p{Ll})о(?= \d)/gu, '$1o')
}

export function localizeDescription(text: string, lang: TextLang, override?: Override): string {
  if (lang === 'bg') return text
  if (filled(override?.shortDescription)) return override.shortDescription.trim()
  return apply(text, DESCRIPTION_RO)
}

/** "10 мм · 8 TPI — Универсална" → "10 mm · 8 TPI — Universală". */
export function localizeSetLine(line: string, lang: TextLang): string {
  if (lang === 'bg') return line
  const match = /^(.*? — )(.+)$/.exec(line)
  const head = (match ? match[1] : '').replace(/мм/g, 'mm')
  const tail = match ? (SET_TAIL_RO[match[2]] ?? match[2]) : line
  return match ? head + tail : line.replace(/мм/g, 'mm')
}

export function localizeMaterial(value: string, lang: TextLang): string {
  if (lang === 'bg') return value
  return MATERIAL_RO[value] ?? value
}

export function localizeCategory(
  category: { slug: string; name: string; description: string },
  lang: TextLang,
  override?: Override,
): { name: string; description: string } {
  if (lang === 'bg') return { name: category.name, description: category.description }
  const known = CATEGORY_RO[category.slug]
  return {
    name: filled(override?.name) ? override.name.trim() : (known?.name ?? category.name),
    description: filled(override?.description) ? override.description.trim() : (known?.description ?? category.description),
  }
}
