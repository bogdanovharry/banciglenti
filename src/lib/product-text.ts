/**
 * Catalogue text in the visitor's language.
 *
 * Product names, descriptions, materials and category names live in the database
 * in Bulgarian, and a Romanian visitor read "Въглеродна банцигова лента 20х0.6
 * L=1425мм" on every card. Rather than 384 hand-translated rows — which would be
 * wrong again the next time a term is corrected — the text is translated where
 * the catalogue is read, from one dictionary here.
 *
 * It works because the text is not free prose. The 356 names with Cyrillic in
 * them are about fifty shapes built from a vocabulary of roughly sixty words
 * ("завои и чист срез", "кутия N бр.", "комплект „Старт""), generated by the
 * seed scripts from the same templates. So the dictionary below is a list of
 * those phrases, applied in order, and correcting a term fixes every product
 * that uses it at once. A Bulgarian string it has no rule for is left as it is:
 * visibly untranslated, which is a bug report, rather than mistranslated.
 *
 * Anything a person wants worded differently for one product is an override
 * (the "Română" group on the product and category in /admin), which wins over
 * the dictionary. The same goes for a product added by staff with a phrase the
 * dictionary has not met.
 *
 * A plain module — no imports — so the verification script can run it directly
 * on every row in the database (scripts in the scratchpad, `node file.ts`).
 *
 * DRAFT Romanian, to be read by a native speaker with the rest of the storefront
 * text. The terms most worth checking are listed with the work that added this.
 */

export type TextLang = 'bg' | 'ro'

/** Bulgarian is what the database holds, and the fallback for every other language. */
export const textLang = (locale: string): TextLang => (locale.startsWith('ro') ? 'ro' : 'bg')

type Rule = [RegExp, string]

const apply = (text: string, rules: Rule[]): string => rules.reduce((t, [pattern, to]) => t.replace(pattern, to), text)

/** Cyrillic letters that look like Latin ones and were typed in place of them ("М42", "СА20"). */
